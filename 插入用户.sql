SELECT '--- 用户统计 ---' AS '';
SELECT COUNT(*) AS total_users FROM `sys_user` WHERE `is_valid` = 1;

SELECT '--- 各角色人数 ---' AS '';
SELECT r.role_name, COUNT(ur.id) AS user_count
FROM `sys_role` r
LEFT JOIN `sys_user_role` ur ON ur.role_id = r.id
GROUP BY r.id, r.role_name
ORDER BY r.sort_order;

SELECT '--- 各部门人数 ---' AS '';
SELECT d.dept_name, COUNT(ud.id) AS user_count
FROM `sys_dept` d
LEFT JOIN `sys_user_dept` ud ON ud.dept_id = d.id
GROUP BY d.id, d.dept_name
ORDER BY d.sort_order;

